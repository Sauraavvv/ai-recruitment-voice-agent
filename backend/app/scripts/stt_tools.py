"""Shared helpers for the STT tools and tests: the clip manifest, audio files, real-time
streaming into a provider, and key-entity matching (plan P4-T3, T8, T9).

Audio lives under artifacts/stt-audio/<set>/<speaker>/<clip id>[+<noise>].wav and is not
committed. `synthetic` is generated by make_stt_clips.py; `real` is recorded by stt_record.py.
"""

import asyncio
import re
import time
import wave
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import numpy as np
import yaml

from app.providers.stt.base import STTProvider
from app.voice import pcm
from app.voice.pcm import FloatAudio

MANIFEST = Path(__file__).resolve().parents[1] / "tests" / "fixtures" / "stt_clips.yaml"
AUDIO_ROOT = Path("artifacts/stt-audio")


@dataclass(frozen=True)
class ClipSpec:
    id: str
    text: str
    say: str
    entities: list[list[str]]
    utterances: int = 1
    pause: bool = False
    noise: list[str] = field(default_factory=list)


@dataclass(frozen=True)
class ClipFile:
    spec: ClipSpec
    set_name: str  # synthetic | real
    speaker: str
    noise: str | None
    path: Path

    @property
    def name(self) -> str:
        return f"{self.set_name}/{self.speaker}/{self.path.stem}"


def load_specs(path: Path = MANIFEST) -> dict[str, ClipSpec]:
    data: dict[str, Any] = yaml.safe_load(path.read_text())
    specs = {}
    for c in data["clips"]:
        specs[c["id"]] = ClipSpec(
            id=c["id"],
            text=c["text"],
            say=c.get("say", c["text"]),
            entities=[[str(a) for a in e] for e in c.get("entities", [])],
            utterances=int(c.get("utterances", 1)),
            pause=bool(c.get("pause", False)),
            noise=list(c.get("noise", [])),
        )
    return specs


def discover(
    sets: tuple[str, ...] = ("synthetic", "real"), root: Path = AUDIO_ROOT
) -> list[ClipFile]:
    specs = load_specs()
    found = []
    for set_name in sets:
        for path in sorted((root / set_name).glob("*/*.wav")):
            clip_id, _, noise = path.stem.partition("+")
            if clip_id in specs:
                found.append(
                    ClipFile(specs[clip_id], set_name, path.parent.name, noise or None, path)
                )
    return found


def read_wav(path: Path) -> tuple[FloatAudio, int]:
    """Mono float audio and its sample rate (16-bit PCM WAVs; stereo is mixed down)."""
    with wave.open(str(path)) as w:
        if w.getsampwidth() != 2:
            raise ValueError(f"{path}: expected 16-bit PCM")
        rate, channels = w.getframerate(), w.getnchannels()
        audio = pcm.pcm16_to_float(w.readframes(w.getnframes()))
    if channels > 1:
        audio = audio.reshape(-1, channels).mean(axis=1).astype(np.float32)
    return audio, rate


def say(text: str, voice: str, rate: int = 16000, *, attempts: int = 6) -> FloatAudio:
    """Speak `text` with macOS `say`. `say` is flaky: the same line sometimes comes out
    truncated, or as seconds of garbage. So render until two renders are identical."""
    import hashlib
    import subprocess
    import tempfile

    seen: dict[str, bytes] = {}
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "say.wav"
        for _ in range(attempts):
            subprocess.run(  # noqa: S603 - fixed arguments, no shell
                ["/usr/bin/say", "-v", voice, f"--data-format=LEI16@{rate}", "-o", str(path), text],
                check=True,
            )
            data = path.read_bytes()
            digest = hashlib.sha256(data).hexdigest()
            if digest in seen:
                path.write_bytes(data)
                audio, got = read_wav(path)
                assert got == rate
                return audio
            seen[digest] = data
    raise RuntimeError(f"`say -v {voice}` gave {attempts} different renders of {text!r}")


def prepare(audio: FloatAudio, rate: int, target_rate: int) -> bytes:
    """linear16 at `target_rate`. 8 kHz also goes through a μ-law round trip, like a phone call."""
    if target_rate == 8000:
        return pcm.phone_band(pcm.float_to_pcm16(audio), rate)
    return pcm.float_to_pcm16(pcm.resample(audio, rate, target_rate))


async def stream_pcm(
    provider: STTProvider,
    data: bytes,
    sample_rate: int,
    *,
    chunk_ms: int = 20,
    realtime: bool = True,
    tail_silence_s: float = 2.5,
    tail_noise_dbfs: float | None = None,
    finalize_at_s: float | None = None,
) -> None:
    """Send linear16 audio in `chunk_ms` frames, paced like a live call when `realtime`, then
    `tail_silence_s` of silence (a caller who has finished and is waiting). `tail_noise_dbfs`
    makes that silence a faint noise floor, as a real phone line has, instead of digital zeros.
    `finalize_at_s`: call `provider.finalize()` once the audio passes that point (what a local
    end-of-speech detector would do)."""
    step = sample_rate * chunk_ms // 1000 * 2
    tail_samples = int(tail_silence_s * sample_rate)
    if tail_noise_dbfs is None:
        tail = b"\0" * (tail_samples * 2)
    else:
        rng = np.random.default_rng(0)
        noise = rng.standard_normal(tail_samples) * 10 ** (tail_noise_dbfs / 20)
        tail = pcm.float_to_pcm16(noise.astype(np.float32))
    audio = data + tail
    frames = [audio[i : i + step] for i in range(0, len(audio), step)]
    finalize = getattr(provider, "finalize", None) if finalize_at_s is not None else None
    started = time.monotonic()
    for i, frame in enumerate(frames):
        await provider.send_audio(frame)
        if finalize is not None and (i + 1) * chunk_ms / 1000 >= (finalize_at_s or 0):
            await finalize()
            finalize = None
        if realtime:
            delay = started + (i + 1) * chunk_ms / 1000 - time.monotonic()
            await asyncio.sleep(max(0.0, delay))


# --- key-entity accuracy -----------------------------------------------------------------------


def speech_end_s(audio: FloatAudio, rate: int, threshold_dbfs: float = -40.0) -> float:
    """Where the last speech in a clean clip ends (20 ms frames above `threshold_dbfs`)."""
    frame = rate // 50
    n = audio.size // frame
    if n == 0:
        return 0.0
    rms = np.sqrt(np.mean(audio[: n * frame].reshape(n, frame) ** 2, axis=1))
    loud = np.nonzero(rms > 10 ** (threshold_dbfs / 20))[0]
    return float((loud[-1] + 1) * frame / rate) if loud.size else 0.0


def normalize_text(text: str) -> str:
    text = text.lower().replace("-", " ")
    text = re.sub(r"(?<=\d),(?=\d)", ",", text)  # keep 12,00,000
    text = re.sub(r"[^\w\s.,:]", " ", text)
    text = re.sub(r"(?<!\d)[.,:]|[.,:](?!\d)", " ", text)  # punctuation, but not inside numbers
    return re.sub(r"\s+", " ", text).strip()


def entity_found(transcript: str, alternatives: list[str]) -> bool:
    norm = normalize_text(transcript)
    for alt in alternatives:
        if re.search(rf"(?<![\w.]){re.escape(normalize_text(alt))}", norm):
            return True
    return False


def entity_hits(transcript: str, entities: list[list[str]]) -> list[bool]:
    return [entity_found(transcript, alternatives) for alternatives in entities]
